/**
 * Exports Foundry artifacts (contracts/out) as typed `as const` ABIs + bytecode into packages/shared/src/abi.
 * Run after `forge build`.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO_ROOT } from "../packages/shared/src/node";

const CONTRACTS = [
  "AgentRegistry",
  "PolicyWallet",
  "PolicyWalletFactory",
  "ArenaCore",
  "ScoreRegistry",
  "ExploitRegistry",
  "GrantPool",
];

const outDir = join(REPO_ROOT, "packages/shared/src/abi");
mkdirSync(outDir, { recursive: true });

const index: string[] = [];
for (const name of CONTRACTS) {
  const art = JSON.parse(readFileSync(join(REPO_ROOT, "contracts/out", `${name}.sol`, `${name}.json`), "utf8"));
  const abiName = name.charAt(0).toLowerCase() + name.slice(1) + "Abi";
  const src =
    `// AUTO-GENERATED by scripts/export-abi.ts — do not edit.\n` +
    `export const ${abiName} = ${JSON.stringify(art.abi, null, 2)} as const;\n\n` +
    `export const ${name}Bytecode = "${art.bytecode.object}" as const;\n`;
  writeFileSync(join(outDir, `${name}.ts`), src);
  index.push(`export * from "./${name}";`);
  console.log(`✓ ${name} (${art.abi.length} entries)`);
}

index.push(
  `export const erc20Abi = ${JSON.stringify(
    [
      { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "a", type: "address" }], outputs: [{ type: "uint256" }] },
      { type: "function", name: "allowance", stateMutability: "view", inputs: [{ name: "o", type: "address" }, { name: "s", type: "address" }], outputs: [{ type: "uint256" }] },
      { type: "function", name: "approve", stateMutability: "nonpayable", inputs: [{ name: "s", type: "address" }, { name: "v", type: "uint256" }], outputs: [{ type: "bool" }] },
      { type: "function", name: "transfer", stateMutability: "nonpayable", inputs: [{ name: "to", type: "address" }, { name: "v", type: "uint256" }], outputs: [{ type: "bool" }] },
      { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ type: "uint8" }] },
    ],
    null,
    2,
  )} as const;`,
);
writeFileSync(join(outDir, "index.ts"), `// AUTO-GENERATED by scripts/export-abi.ts\n${index.join("\n")}\n`);
console.log(`ABIs written to ${outDir}`);
