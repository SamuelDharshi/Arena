/**
 * One-command LOCAL TEST HARNESS: anvil (1s blocks, like Arc) + a throwaway 6-decimal test token standing in
 * for USDC (Arc's real USDC relies on Arc-native precompiles that don't exist outside Arc nodes), then the real
 * deploy + seed scripts. Writes .env.local and deployments/31337.json; state lives in data-local/.
 *
 *   pnpm local:up        then: ARENA_ENV=local pnpm dev
 */
import { spawn, execSync } from "node:child_process";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createPublicClient, createWalletClient, http, parseEther } from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { foundry } from "viem/chains";
import { REPO_ROOT } from "../packages/shared/src/node";

const RPC = "http://127.0.0.1:8545";
const DEV_KEY = "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80" as const; // anvil account #0

const pub = createPublicClient({ chain: foundry, transport: http(RPC) });

async function rpcUp(): Promise<boolean> {
  try {
    await pub.getChainId();
    return true;
  } catch {
    return false;
  }
}

async function main() {
  if (!existsSync(join(REPO_ROOT, ".env"))) execSync("pnpm keys", { cwd: REPO_ROOT, stdio: "inherit" });

  if (!(await rpcUp())) {
    console.log("Starting anvil (chain 31337, 1s blocks)…");
    const child = spawn("anvil", ["--chain-id", "31337", "--block-time", "1", "--port", "8545", "--silent"], {
      detached: true,
      stdio: "ignore",
      env: { ...process.env, FOUNDRY_DISABLE_NIGHTLY_WARNING: "1" },
    });
    child.unref();
    for (let i = 0; i < 30 && !(await rpcUp()); i++) await new Promise((r) => setTimeout(r, 500));
    // Fresh chain → old local state and deployment are stale.
    rmSync(join(REPO_ROOT, "data-local"), { recursive: true, force: true });
    rmSync(join(REPO_ROOT, "deployments", "31337.json"), { force: true });
  }

  console.log("Deploying local test token…");
  const out = execSync(
    `forge create test/Base.t.sol:TestUSDC --rpc-url ${RPC} --private-key ${DEV_KEY} --broadcast`,
    { cwd: join(REPO_ROOT, "contracts"), env: { ...process.env, FOUNDRY_DISABLE_NIGHTLY_WARNING: "1" } },
  ).toString();
  const token = out.match(/Deployed to: (0x[0-9a-fA-F]{40})/)?.[1];
  if (!token) throw new Error(`token deploy failed:\n${out}`);

  writeFileSync(
    join(REPO_ROOT, ".env.local"),
    `# LOCAL TEST HARNESS ONLY — generated by \`pnpm local:up\`. Real target: Arc testnet via .env.
ARC_RPC_URL=${RPC}
ARC_CHAIN_ID=31337
USDC_ADDRESS=${token}
GATEWAY_PORT=9787
GATEWAY_PUBLIC_URL=http://localhost:9787
AGENTS_PORT=9788
AGENTS_PUBLIC_URL=http://localhost:9788
NEXT_PUBLIC_GATEWAY_URL=http://localhost:9787
`,
  );

  const envText = readFileSync(join(REPO_ROOT, ".env"), "utf8");
  const deployerKey = envText.match(/^DEPLOYER_KEY=(0x[0-9a-fA-F]{64})/m)?.[1] as `0x${string}`;
  const deployer = privateKeyToAccount(deployerKey).address;
  const dev = createWalletClient({ account: privateKeyToAccount(DEV_KEY), chain: foundry, transport: http(RPC) });
  await pub.waitForTransactionReceipt({ hash: await dev.sendTransaction({ to: deployer, value: parseEther("100") }) });
  await pub.waitForTransactionReceipt({
    hash: await dev.writeContract({
      address: token as `0x${string}`,
      abi: [{ type: "function", name: "mint", stateMutability: "nonpayable", inputs: [{ name: "to", type: "address" }, { name: "a", type: "uint256" }], outputs: [] }],
      functionName: "mint",
      args: [deployer, 1_000_000_000n],
    }),
  });
  console.log(`Funded deployer ${deployer} with 100 ETH gas + 1,000 test tokens`);

  const run = (cmd: string) => execSync(cmd, { cwd: REPO_ROOT, stdio: "inherit", env: { ...process.env, ARENA_ENV: "local" } });
  run("pnpm deploy:arc --force");
  run("pnpm seed:arc");
  console.log("\nLocal stack ready. Start services:  ARENA_ENV=local pnpm dev   → web http://localhost:3000");
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
